#!/usr/bin/env python3
"""Generate Gateterm/I18n/AndroidStrings.swift from the Android string resources.

Android stays the source of truth for shared wording; iOS-only wording and the few
Android-specific sentences are overridden in L10n.swift. Run after editing strings.xml:
    python3 clients/ios/scripts/gen-strings.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent.parent / "android/app/src/main/res"
OUT = HERE.parent / "Gateterm/I18n/AndroidStrings.swift"


def load(path):
    out = {}
    for node in ET.parse(path).getroot().findall("string"):
        text = "".join(node.itertext())
        text = text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")
        # Android positional `%1$s` -> Foundation `%1$@` (Swift Strings are objects).
        text = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", text)
        out[node.get("name")] = text
    return out


def swift(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


zh = load(RES / "values/strings.xml")
en = load(RES / "values-en/strings.xml")
lines = ["// Generated by clients/ios/scripts/gen-strings.py from the Android resources. Do not edit.", "",
         "enum AndroidStrings {"]
for name, table in (("zh", zh), ("en", {**zh, **en})):
    lines.append(f"    static let {name}: [String: String] = [")
    for key in sorted(table):
        lines.append(f"        {swift(key)}: {swift(table[key])},")
    lines.append("    ]")
lines.append("}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({len(zh)} keys)")
