            ("╌┄┈", [1, 7, 6, 9, 10, 7, 15, 9]),
            ("╍┅┉", [1, 6, 6, 10, 10, 6, 15, 10]),
            ("╎┆┊", [7, 1, 9, 6, 7, 10, 9, 15]),
            ("╏┇┋", [6, 1, 10, 6, 6, 10, 10, 15]),
