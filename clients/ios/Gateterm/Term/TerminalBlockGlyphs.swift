            ("╠", [5, 0, 7, 16, 9, 0, 11, 7, 9, 9, 11, 16, 9, 5, 16, 7, 9, 9, 16, 11]),
            ("╡", [7, 0, 9, 16, 0, 5, 9, 7, 0, 9, 9, 11]),
            ("╢", [5, 0, 7, 16, 9, 0, 11, 16, 0, 7, 7, 9]),
            ("╣", [9, 0, 11, 16, 5, 0, 7, 7, 5, 9, 7, 16, 0, 5, 7, 7, 0, 9, 7, 11]),
            ("╤", [0, 5, 16, 7, 0, 9, 16, 11, 7, 9, 9, 16]),
